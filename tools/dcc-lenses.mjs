// Converts the lens and glass catalog of DCC-Lab/RayTracing (MIT License, Copyright (c) 2019-2022
// DCCLab and Daniel C. Cote, https://github.com/DCC-Lab/RayTracing) into the CSV files the renderer
// reads: src/main/resources/optics/glasses.csv and lenses.csv.
//
//   git clone --depth 1 https://github.com/DCC-Lab/RayTracing <dir>
//   node tools/dcc-lenses.mjs <dir>
//
// Glasses: each n(x) of raytracing/materials.py is read as either three Sellmeier terms
// B / (1 - C / x^2) (or 1 + C / x^2, or 1 - (c / x)^2, all brought to the first form) or Schott's
// polynomial n^2 = A0 + A1 x^2 + A2 x^-2 + A3 x^-4 + A4 x^-6 + A5 x^-8; the coefficients are then
// checked against the original expression, evaluated as JavaScript, at five wavelengths.
// Lenses: the keyword arguments of every super().__init__ in thorlabs.py and eo.py.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const source = process.argv[2];
if (!source) throw new Error('usage: node tools/dcc-lenses.mjs <RayTracing checkout>');
const pkg = path.join(source, 'raytracing');
const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'main', 'resources', 'optics');
fs.mkdirSync(out, { recursive: true });

const header = (what) => [
  `# ${what} from DCC-Lab/RayTracing (https://github.com/DCC-Lab/RayTracing),`,
  '# MIT License, Copyright (c) 2019-2022 DCCLab and Daniel C. Cote.',
  '# Generated by tools/dcc-lenses.mjs - do not edit by hand.',
];

// ---- glasses ----
const materials = fs.readFileSync(path.join(pkg, 'materials.py'), 'utf8');
const NUM = String.raw`[0-9]*\.?[0-9]+(?:[eE][-+]?[0-9]+)?`;
const glasses = new Map();
for (const block of materials.split(/^class /m).slice(1)) {
  const name = block.match(/^(\w+)\(Material\)/)?.[1];
  if (!name || name === 'Air') continue;
  const expr = block.match(/n\s*=\s*(\([\s\S]*?\)\s*\*\*\s*\.5)/)?.[1]?.replace(/\s+/g, ' ');
  if (!expr) throw new Error(`no formula for ${name}`);
  const abbe = Number(block.match(/def abbeNumber[\s\S]*?return\s+(NUM_PLACEHOLDER)/.source.replace('NUM_PLACEHOLDER', NUM))?.[1] ?? NaN);
  let formula, k;
  const terms = [...expr.matchAll(new RegExp(String.raw`(${NUM})\s*/\s*\(\s*1\s*([-+])\s*(?:(${NUM})\s*/\s*x\s*\*\*\s*2|\(\s*(${NUM})\s*/\s*x\s*\)\s*\*\*\s*2)\s*\)`, 'g'))];
  if (terms.length === 3) {
    formula = 'sellmeier';
    const b = terms.map(t => Number(t[1]));
    const c = terms.map(t => (t[3] !== undefined ? Number(t[3]) : Number(t[4]) ** 2) * (t[2] === '-' ? 1 : -1));
    k = [b[0], b[1], b[2], c[0], c[1], c[2]];
  } else {
    formula = 'schott';
    const inner = expr.replace(/^\(\s*/, '').replace(/\)\s*\*\*\s*\.5$/, '');
    k = [0, 0, 0, 0, 0, 0];
    const powers = { '2': 1, '-2': 2, '-4': 3, '-6': 4, '-8': 5 };
    for (const t of inner.matchAll(new RegExp(String.raw`([-+]?)\s*(${NUM})(?:\s*\*\s*x\s*\*\*\s*(-?\d))?`, 'g'))) {
      const v = Number(t[2]) * (t[1] === '-' ? -1 : 1);
      if (t[3] === undefined) k[0] = v; else k[powers[t[3]]] = v;
    }
  }
  const n = (x) => formula === 'sellmeier'
    ? Math.sqrt(1 + k[0] / (1 - k[3] / (x * x)) + k[1] / (1 - k[4] / (x * x)) + k[2] / (1 - k[5] / (x * x)))
    : Math.sqrt(k[0] + k[1] * x ** 2 + k[2] * x ** -2 + k[3] * x ** -4 + k[4] * x ** -6 + k[5] * x ** -8);
  const original = new Function('x', `return ${expr};`);
  for (const x of [0.4, 0.486, 0.5876, 0.6563, 0.75]) {
    if (Math.abs(n(x) - original(x)) > 1e-9) throw new Error(`${name}: ${n(x)} vs ${original(x)} at ${x}`);
  }
  glasses.set(name, { formula, k, abbe, n });
}
const glassLines = [...header('Glasses: refractive index n(lambda in microns)'),
  '# sellmeier: n^2 = 1 + k0/(1-k3/x^2) + k1/(1-k4/x^2) + k2/(1-k5/x^2)',
  '# schott:    n^2 = k0 + k1 x^2 + k2 x^-2 + k3 x^-4 + k4 x^-6 + k5 x^-8',
  'name,formula,k0,k1,k2,k3,k4,k5,abbe'];
for (const [name, g] of glasses) glassLines.push([name.replace(/_/g, '-'), g.formula, ...g.k, Number.isNaN(g.abbe) ? '' : g.abbe].join(','));
fs.writeFileSync(path.join(out, 'glasses.csv'), glassLines.join('\n') + '\n');

// ---- lenses ----
const value = (args, key) => {
  const m = args.match(new RegExp(String.raw`(?:^|[,(\s])${key}\s*=\s*("[^"]*"|'[^']*'|float\(\s*["'][-+]?inf["']\s*\)|[\w.+-]+)`));
  if (!m) return undefined;
  const v = m[1];
  if (/^float/.test(v)) return v.includes('-inf') ? '-inf' : 'inf';
  if (/^["']/.test(v)) return v.slice(1, -1);
  return v === 'None' ? undefined : v;
};
const lenses = [];
for (const file of ['thorlabs.py', 'eo.py']) {
  const text = fs.readFileSync(path.join(pkg, file), 'utf8');
  for (const m of text.matchAll(/^class (\w+)\((AchromatDoubletLens|SingletLens)\)[\s\S]*?super\([^)]*\)\s*\.\s*__init__\(([\s\S]*?)\)\s*\n\s*\n/gm)) {
    const [, cls, kind, args] = m;
    const single = kind === 'SingletLens';
    const glass = (g) => {
      if (g === undefined) return '';
      if (!glasses.has(g)) throw new Error(`${cls}: unknown glass ${g}`);
      return g.replace(/_/g, '-');
    };
    const row = {
      name: (value(args, 'label') ?? cls).replace(/^EO #/, 'EO-').replace(/_/g, '-'),
      kind: single ? 'singlet' : 'doublet',
      f: value(args, single ? 'f' : 'fa'), fb: value(args, 'fb'),
      R1: value(args, 'R1'), R2: value(args, 'R2'), R3: single ? '' : value(args, 'R3'),
      tc1: value(args, single ? 'tc' : 'tc1'), tc2: single ? '' : value(args, 'tc2'),
      te: value(args, 'te'), diameter: value(args, 'diameter'),
      glass1: glass(value(args, single ? 'mat' : 'mat1')), glass2: single ? '' : glass(value(args, 'mat2')),
      n1: value(args, single ? 'n' : 'n1') ?? '', n2: single ? '' : (value(args, 'n2') ?? ''),
      reference: value(args, 'wavelengthRef') ?? '0.5876',
      url: value(args, 'url') ?? '',
    };
    for (const key of ['f', 'fb', 'R1', 'R2', 'tc1', 'te', 'diameter']) if (row[key] === undefined) throw new Error(`${cls}: no ${key}`);
    // The catalog's n1/n2 sometimes hold the design wavelength (0.5876) instead of an index; only
    // indices above 1 are kept, and a lens needs either its glass or one.
    for (const [n, g] of [['n1', 'glass1'], ['n2', 'glass2']]) {
      if (row[n] !== '' && Number(row[n]) <= 1) row[n] = '';
      if (!(n === 'n2' && single) && row[n] === '' && row[g] === '') throw new Error(`${cls}: no glass or index for ${n}`);
    }
    lenses.push(row);
  }
}
// Not every entry is right: many of the near-infrared doublets (-B, -C, -AB without -ML) have radii
// that give their quoted back focal length at no wavelength at all, and a few classes are defined
// twice with different numbers. Each entry is checked as DCC itself checks it, by ray matrices - a
// paraxial ray through the surfaces - over its series' design band (Thorlabs: -A 587.6 nm, -B
// 706.5-1015 nm, -C 1050-1620 nm, -AB 400-1100 nm); it is kept when its back focal length comes
// within 1% of the catalog's somewhere in the band, and the wavelength where it comes closest is
// written as its reference. Of a class defined twice, the later right one wins, as in Python.
function backFocalLength(l, microns) {
  const radii = [l.R1, l.R2, l.R3].filter(r => r !== '').map(r => (r === 'inf' ? Infinity : r === '-inf' ? -Infinity : Number(r)));
  const thick = [l.tc1, l.tc2].filter(t => t !== '').map(Number);
  const index = (g, n) => (g !== '' ? glasses.get(g.replace(/-/g, '_')).n(microns) : Number(n));
  const media = [1, index(l.glass1, l.n1), ...(l.kind === 'doublet' ? [index(l.glass2, l.n2)] : []), 1];
  // (y, n u): refraction adds -y (n2 - n1) / R to n u, a gap of t in glass n adds t (n u) / n to y.
  let [A, B, C, D] = [1, 0, 0, 1];
  radii.forEach((R, k) => {
    const power = (media[k + 1] - media[k]) / R;
    [C, D] = [C - power * A, D - power * B];
    if (k < thick.length) [A, B] = [A + (thick[k] / media[k + 1]) * C, B + (thick[k] / media[k + 1]) * D];
  });
  return -A / C;
}
function band(name) {
  const series = name.match(/-(A|AB|B|C)(?:-ML)?$/)?.[1] ?? 'A';
  return { A: [0.5876, 0.5876], AB: [0.4, 1.1], B: [0.7065, 1.015], C: [1.05, 1.62] }[series];
}
const byName = new Map();
const dropped = [];
for (const l of lenses) {
  const [from, to] = band(l.name);
  let best = null;
  for (let x = from; x <= to + 1e-9; x += 0.0025) {
    const error = Math.abs(backFocalLength(l, x) - Number(l.fb)) / Math.abs(Number(l.fb));
    if (!best || error < best.error) best = { x, error };
  }
  if (best.error <= 0.01) {
    l.reference = best.x.toFixed(4);
    byName.delete(l.name);
    byName.set(l.name, l);
  } else {
    dropped.push(`${l.name} (${(best.error * 100).toFixed(1)}% off)`);
  }
}
const kept = [...byName.values()];
const columns = Object.keys(kept[0]);
const lensLines = [...header('Lenses (millimetres; radii positive when the centre of curvature lies after the vertex)'),
  '# reference: the wavelength (microns) in the design band where fb is met - see tools/dcc-lenses.mjs',
  columns.join(','), ...kept.map(l => columns.map(c => l[c]).join(','))];
fs.writeFileSync(path.join(out, 'lenses.csv'), lensLines.join('\n') + '\n');
console.log(`${glasses.size} glasses, ${kept.length} lenses (${kept.filter(l => l.kind === 'singlet').length} singlets) -> ${out}`);
console.log(`dropped ${dropped.length} entries whose radii miss their focal length:\n  ${dropped.join('\n  ')}`);
